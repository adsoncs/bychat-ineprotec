-- Desconto em fatura já gerada, com registro de quem deu, quem aprovou e motivo.
CREATE TABLE `bychat_enrollment_descontos` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `registrationId` INTEGER NOT NULL,
  `leadId` INTEGER NULL,
  `chave` VARCHAR(80) NOT NULL,
  `fatura` VARCHAR(191) NOT NULL,
  `meio` VARCHAR(20) NULL,
  `externalId` VARCHAR(191) NULL,
  `modo` VARCHAR(12) NOT NULL,
  `percentual` DECIMAL(5, 2) NULL,
  `couponId` INTEGER NULL,
  `couponCode` VARCHAR(50) NULL,
  `valorAntesCentavos` INTEGER NOT NULL,
  `descontoCentavos` INTEGER NOT NULL,
  `valorDepoisCentavos` INTEGER NOT NULL,
  `situacao` VARCHAR(20) NOT NULL DEFAULT 'aplicado',
  `trocaId` INTEGER NULL,
  `motivo` TEXT NOT NULL,
  `aprovadoPor` VARCHAR(191) NULL,
  `criadoPorUserId` INTEGER NULL,
  `criadoPorNome` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX `bychat_enrollment_descontos_registrationId_idx`(`registrationId`),
  INDEX `bychat_enrollment_descontos_leadId_idx`(`leadId`),
  INDEX `bychat_enrollment_descontos_createdAt_idx`(`createdAt`),
  INDEX `bychat_enrollment_descontos_couponId_idx`(`couponId`),
  INDEX `bychat_enrollment_descontos_trocaId_idx`(`trocaId`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
