// Inscrição com taxa → PIX na tela → confirmação → status atualizado.
import { chromium } from '@playwright/test'
const B='http://127.0.0.1:3110', linha=(a,b)=>console.log(`  ${String(a).padEnd(44)} ${b}`)
const b=await chromium.launch()
const p=await (await b.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2})).newPage()
const erros=[]
p.on('pageerror', e=>erros.push(String(e)))
p.on('response', r=>{ if(r.status()>=400) erros.push(`${r.status()} ${r.url().replace(B,'')}`) })

await p.goto(`${B}/portal/inscricao`, { waitUntil: 'networkidle' })
await p.evaluate(()=>localStorage.clear()); await p.reload({waitUntil:'networkidle'})
await p.waitForSelector('.cartao h2')
await p.fill('input[name="nome"]', 'Diego Moraes Batista')
await p.fill('input[name="cpf"]', '168.995.350-09')
await p.fill('input[name="email"]', 'diego.moraes.batista@example.com')
await p.fill('input[name="whatsapp"]', '62994445566')
await p.click('button.principal'); await p.waitForTimeout(600)
await p.locator('.curso').first().click(); await p.waitForTimeout(300)
await p.click('button.principal'); await p.waitForTimeout(600)
await p.click('button.principal')
await p.waitForSelector('.fim', { timeout: 15000 })
linha('inscrição', await p.textContent('.fim .codigo'))

console.log('\n── etapa de pagamento ──')
await p.waitForSelector('.opcao-pagamento', { timeout: 8000 })
linha('opções oferecidas', (await p.locator('.opcao-pagamento b').allTextContents()).join(' · '))
await p.locator('.opcao-pagamento').first().click()  // PIX
await p.waitForTimeout(2500)
linha('título', JSON.stringify(await p.textContent('.cartao h2:has-text("PIX")').catch(()=>null)))
linha('valor da taxa', JSON.stringify((await p.locator('.cartao .sub').last().textContent())?.trim().slice(0,40)))
linha('QR renderizado', (await p.locator('.qr-caixa img').count()) ? 'sim' : 'não')
const qr = await p.locator('.qr-caixa img').getAttribute('src').catch(()=>null)
linha('   origem da imagem', qr ? qr.slice(0,30)+'…' : '—')
linha('aviso de ambiente de teste', (await p.locator('.aviso.info').count()) ? 'sim' : 'não')
const codigo = await p.locator('.codigo-longo').textContent().catch(()=>null)
linha('payload PIX começa com', JSON.stringify(codigo?.slice(0,24)))

console.log('\n── confirmação ──')
await p.locator('button:has-text("Simular pagamento")').click()
await p.waitForSelector('h2:has-text("Pagamento confirmado")', { timeout: 10000 })
linha('tela final', JSON.stringify(await p.textContent('h2:has-text("Pagamento confirmado")')))
await p.screenshot({ path: '/tmp/pagamento.png', fullPage: true })
linha('erros', erros.length ? JSON.stringify(erros.slice(0,3)) : 'nenhum')
await b.close()
